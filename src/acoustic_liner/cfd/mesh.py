"""Geometry and blockMesh primitives of the axisymmetric neck rig: neck and tube radii, the wedge angle,
the vertex and block builders, and the OpenFOAM file header.
"""
from __future__ import annotations

import os, argparse, math


# ---- flagship bank-2 neck (metres) ---------------------------------------
R_NECK = 7.236e-3      # neck radius
L_NECK = 25.6137e-3    # neck length


# ---- rig tubes -----------------------------------------------------------
# Duct length chosen so the rig's OWN neck+duct Helmholtz resonance sits well
# ABOVE the 126.5 Hz measurement frequency (short ducts -> small compliance ->
# resonance ~450 Hz), so the neck is driven sub-resonantly and the response
# converges in a few cycles instead of ringing. Long enough for the measurement
# planes to clear the (small, at these velocities) orifice near-field. Stage 4
# proves length-independence.
R_TUBE  = 3.0 * R_NECK     # tube radius (room for the orifice jet on each side)
WEDGE_DEG = 5.0


# --------------------------------------------------------------------------
# wedge vertex registry (axis=Z, radial=X, wedge splits +/-Y)
# --------------------------------------------------------------------------
class Verts:
    def __init__(self, half_deg):
        self.h = math.radians(half_deg / 2.0)
        self._idx = {}; self._list = []

    def _pt(self, r, z, side):
        x = r * math.cos(self.h); y = side * r * math.sin(self.h)
        key = (round(x, 10), round(y, 10), round(z, 10))
        if key not in self._idx:
            self._idx[key] = len(self._list); self._list.append((x, y, z))
        return self._idx[key]

    def corner(self, r, z):
        return self._pt(r, z, -1), self._pt(r, z, +1)

    def dump(self):
        return "\n".join(f"    ({x:.9g} {y:.9g} {z:.9g})" for x, y, z in self._list)


class Block:
    def __init__(self, V, r0, r1, z0, z1, nr, nz, gr, gz):
        self.nr, self.nz, self.gr, self.gz = nr, nz, gr, gz
        self.a0m, self.a0p = V.corner(r0, z0)
        self.a1m, self.a1p = V.corner(r1, z0)
        self.a2m, self.a2p = V.corner(r1, z1)
        self.a3m, self.a3p = V.corner(r0, z1)

    def hexs(self):
        # plus-side face first -> right-handed (positive volume) wedge cells
        v = (self.a0p, self.a1p, self.a2p, self.a3p,
             self.a0m, self.a1m, self.a2m, self.a3m)
        return ("    hex ({} {} {} {} {} {} {} {}) ({} {} 1) "
                "simpleGrading ({} {} 1)").format(*v, self.nr, self.nz, self.gr, self.gz)

    def face_rlo(self): return (self.a0m, self.a3m, self.a3p, self.a0p)  # r=r0 (axis)
    def face_rhi(self): return (self.a1m, self.a1p, self.a2p, self.a2m)  # r=r1 (outer)
    def face_zlo(self): return (self.a0m, self.a0p, self.a1p, self.a1m)  # z=z0
    def face_zhi(self): return (self.a3m, self.a2m, self.a2p, self.a3p)  # z=z1
    def face_wedge_m(self): return (self.a0m, self.a1m, self.a2m, self.a3m)
    def face_wedge_p(self): return (self.a0p, self.a3p, self.a2p, self.a1p)


def q(face): return "        (" + " ".join(str(i) for i in face) + ")"


