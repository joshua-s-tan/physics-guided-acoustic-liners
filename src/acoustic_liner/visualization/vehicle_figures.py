NOTES = {}      # image name -> {"titles": [...], "notes": [...]}, written to TITLES.md / FOOTNOTES.md


def save(fig, path, **kw):
    """Save with no title, suptitle or footnote on the image. Their text goes to TITLES.md / FOOTNOTES.md in the same folder
    (bookkeeping, and the source for the written captions). Footnotes are figure-level texts and any axes text
    tagged gid="footnote"."""
    path = Path(path)
    titles, notes = [], []
    if fig._suptitle is not None and fig._suptitle.get_text():
        titles.append(fig._suptitle.get_text())
        fig._suptitle.remove()
        fig._suptitle = None
    for a in fig.axes:
        for loc in ("left", "center", "right"):
            if a.get_title(loc):
                titles.append(a.get_title(loc))
                a.set_title("", loc=loc)
        for t in list(a.texts):
            if t.get_gid() == "footnote":
                notes.append(t.get_text())
                t.remove()
    for t in list(fig.texts):
        notes.append(t.get_text())
        t.remove()
    NOTES[path.name] = dict(titles=titles, notes=notes)
    _write_readme(path.parent)
    kw.setdefault("bbox_inches", "tight")
    fig.savefig(path, **kw)


def _write_readme(folder):
    src = Path(__file__).resolve().relative_to(ROOT).as_posix()
    for fname, key, head, what in (
            ("TITLES.md", "titles", "Figure and panel titles",
             "The images carry no titles; the title of each figure and panel (in drawing order) is kept here."),
            ("FOOTNOTES.md", "notes", "Figure footnotes",
             "The images carry no footnotes; each figure's source line and notes are kept here.")):
        lines = [f"# {head}", "", f"Bookkeeping, generated by `{src}`. {what} Image hashes are in "
                 "`figure_manifest.json`.", ""]
        for name in sorted(NOTES):
            lines += [f"## {name}", ""]
            lines += ["- " + " ".join(t.split()) for t in NOTES[name][key]] or ["- (none)"]
            lines.append("")
        (Path(folder) / fname).write_text("\n".join(lines), encoding="utf-8")



def load(p):
    return json.loads(Path(p).read_text(encoding="utf-8"))


def stat(v):
    return load(VDIR / VEH[v]["dir"] / "statistical_followup/_stat_cfd_result.json")


def pairs(v):
    return load(VDIR / VEH[v]["dir"] / "statistical_followup/_pairs.json")["pairs"]


def selection(v):
    return load(VDIR / VEH[v]["dir"] / "statistical_followup/_selection_check/_targeted_selection.json")


def stamp(fig, text):
    fig.text(0.01, 0.005, text, fontsize=7, color="0.4", ha="left", va="bottom")


SRC = "Source: frozen records; simulation-based, not experimentally validated."


# ---------------------------------------------------------------- F1: impedance vs velocity
def fig_impedance(v, out):
    r = stat(v)
    sel = {p["name"] for p in pairs(v)}
    fig, ax = plt.subplots(2, 4, figsize=(16, 7), sharex="col")
    for j, b in enumerate(sorted(r["banks"])):
        cs = sorted((c for c in r["cases"] if c["bank_id"] == b), key=lambda c: c["u_target"])
        for i, q in enumerate(("R", "X")):
            a = ax[i, j]
            ok = [c for c in cs if c["state"] == "valid"]
            bad = [c for c in cs if c["state"] != "valid"]
            u = [c["row"]["u_amp"] for c in ok]
            y = [c["row"][f"{q}_phasor"] for c in ok]
            h = [c["row"][f"h_{q}"] for c in ok]
            a.errorbar(u, y, yerr=h, fmt="o-", color=BANK_C[j], ms=4, capsize=3, label="valid (±95 % half-width)")
            for c in bad:
                est = (c.get("report") or {}).get("estimate") or {}
                if q in est:
                    a.plot(est.get("u_amp", c["u_target"]), est[q], "x", color="k", ms=8)
            a.plot([], [], "x", color="k", label="nominal-table case failed block gates")
            for c in ok:
                if c["name"] in sel:
                    a.plot(c["row"]["u_amp"], c["row"][f"{q}_phasor"], "s", mfc="none", mec="m", ms=11)
            a.plot([], [], "s", mfc="none", mec="m", label="five-case sensitivity source")
            bk = r["banks"][b]
            a.axvspan(bk["U_star_lo"], bk["U_star_hi"], color="0.85", label="U* (broadband - tone)")
            a.set_xscale("log")
            a.grid(alpha=0.3)
            if i == 0:
                a.set_title(f"bank {b}  ({len(ok)} valid / {len(cs)})")
            if j == 0:
                a.set_ylabel(f"{q} (Rayl)")
            if i == 1:
                a.set_xlabel("neck velocity amplitude U (m/s)")
    ax[0, 0].legend(fontsize=7, loc="upper left")
    fig.suptitle(f"{VEH[v]['label']}: block-estimated neck impedance (statistical table, pre-continuation)")
    stamp(fig, SRC)
    fig.tight_layout(rect=(0, 0.02, 1, 0.96))
    save(fig, out / f"{v}_F1_impedance_vs_U.png", dpi=130)
    plt.close(fig)


# ---------------------------------------------------------------- F2: gate margins
def gate_ratios(est):
    z = est["z_mag"]
    return [abs(est["trend_R"]) / GATE["trend"], abs(est["trend_X"]) / GATE["trend"],
            abs(est["half_shift"]) / GATE["half_shift"],
            est["h_R"] / z / GATE["halfwidth"], est["h_X"] / z / GATE["halfwidth"],
            max(est["thd_p"], est["thd_u"]) / GATE["thd"]]


GCOLS = ["trend R", "trend X", "half-shift", "h_R/|Z|", "h_X/|Z|", "THD"]


def fig_gates(v, out, extra=None):
    r = stat(v)
    rows, names = [], []
    for c in sorted(r["cases"], key=lambda c: (c["bank_id"], c["u_target"])):
        est = (c.get("report") or {}).get("estimate")
        if est:
            rows.append(gate_ratios(est))
            names.append(f"{c['bank_id']} U={c['u_target']:g}" + ("" if c["state"] == "valid" else "  [table FAIL]"))
    for n, est in (extra or []):
        rows.append(gate_ratios(est))
        names.append(n + ("  [variant FAIL]" if max(gate_ratios(est)) > 1 else ""))
    m = np.array(rows)
    fig, ax = plt.subplots(figsize=(8, 0.28 * len(names) + 1.8))
    im = ax.imshow(np.clip(m, 0, 2), cmap="RdYlGn_r", vmin=0, vmax=2, aspect="auto")
    for (i, j), val in np.ndenumerate(m):
        ax.text(j, i, f"{val:.2f}", ha="center", va="center", fontsize=6.5,
                color="k" if val < 1.6 else "w", weight="bold" if val > 1 else "normal")
    ax.set_xticks(range(len(GCOLS)), GCOLS)
    ax.set_yticks(range(len(names)), names, fontsize=7)
    fig.colorbar(im, ax=ax, label="metric / threshold  (>1 fails)", shrink=0.6)
    ax.set_title(f"{VEH[v]['label']}: block-gate usage per case (existing histories)", fontsize=10)
    stamp(fig, SRC + "  Above the line: nominal statistical table. Below: five-case sensitivity variants "
          "(separate failures; these can occur below 20 m/s).")
    if extra:
        ax.axhline(len(names) - len(extra) - 0.5, color="k", lw=1.5)
    fig.tight_layout(rect=(0, 0.02, 1, 1))
    save(fig, out / f"{v}_F2_gate_margins.png", dpi=130)
    plt.close(fig)


# ---------------------------------------------------------------- F3: sensitivity pairs, block series
def pair_estimates(v):
    from ..vehicles import cfd_supplemental as S
    res = []
    for p in pairs(v):
        sd = ROOT / p["source_dir"].replace("\\", "/")
        vd = ROOT / p["variant_dir"].replace("\\", "/")
        res.append((p, S.block_estimate(str(sd)), S.block_estimate(str(vd))))
    return res


def fig_pairs(v, out, pe):
    n = len(pe)
    fig, ax = plt.subplots(2, n, figsize=(3.4 * n, 6.2))
    for j, (p, es, ev) in enumerate(pe):
        for i, q in enumerate(("R", "X")):
            a = ax[i, j]
            for est, lab, col in ((es, "source (nominal)", "tab:blue"), (ev, "variant (" + p["group"] + ")", "tab:red")):
                y = np.array(est[f"{q}_blocks"])
                k = np.arange(est["discarded"] + 1, est["discarded"] + 1 + len(y))
                a.plot(k, y, "o-", color=col, ms=3.5, label=lab)
                s, c0 = np.polyfit(k, y, 1)
                a.plot(k, s * k + c0, "--", color=col, lw=1)
                a.axhspan(est[q] - est[f"h_{q}"], est[q] + est[f"h_{q}"], color=col, alpha=0.08)
            a.grid(alpha=0.3)
            if i == 0:
                st = "CONTINUED" if p["continue_pair"] else "passes as is"
                fl = ",".join(p["variant"]["failed"] + p["source"]["failed"]) or "-"
                a.set_title(f"{p['case']} [{p['slot']}]\n{st}; failed: {fl}", fontsize=8)
            else:
                a.set_xlabel("cycle")
            if j == 0:
                a.set_ylabel(f"block {q}_k (Rayl)")
    ax[0, 0].legend(fontsize=7)
    fig.suptitle(f"{VEH[v]['label']}: five-case sensitivity pairs, per-cycle block impedance "
                 "(dashed: linear trend; band: mean ± half-width)", fontsize=10)
    stamp(fig, SRC + "  Pre-continuation histories only; cycles counted from 1 (cycles 1-4 discarded). The fitted "
          "trend is strongly influenced by one or two cycles; the continuation tests whether that persists.\n"
          "Continuation analysis window: cycles 14-25 (last 12 of 25; cycle 13 = settling), fixed in "
          "docs/VEHICLE-STATISTICAL-FOLLOWUP-PROTOCOL.md (commit c717e41) before any continuation was run.")
    fig.tight_layout(rect=(0, 0.04, 1, 0.94))
    save(fig, out / f"{v}_F3_sensitivity_pairs.png", dpi=130)
    plt.close(fig)


# ---------------------------------------------------------------- F4: FEM vs target
def fig_fem(out):
    fig, ax = plt.subplots(1, 2, figsize=(13, 4.8))
    # Falcon first supplemental (frozen SUPPLEMENTAL UNRESOLVED record's FEM)
    f = load(VDIR / VEH["falcon"]["dir"] / "supplemental_statistical/_supp_fem.json")
    a = ax[0]
    for t, mk in (("broadband", "o"), ("resonant_tone", "s")):
        for k, tab in enumerate(sorted(f["fem"])):
            d = f["fem"][tab][t]
            ms = sorted(d, key=float, reverse=True)
            a.plot([float(m) for m in ms], [d[m] for m in ms], mk + "-", ms=4, lw=1,
                   color=plt.cm.tab10(k), alpha=0.9 if t == "broadband" else 0.6,
                   label=f"table {tab} / {t.replace('_', ' ')}")
    a.set_title("Falcon: first supplemental FEM, west_range / equal_blocked_area_solid (primary)\n"
                "5 impedance tables x 2 forcings; record outcome: SUPPLEMENTAL UNRESOLVED", fontsize=9)
    # Atlas primary corrected FEM (deterministic table)
    c = load(VDIR / VEH["atlas"]["dir"] / "nominal_comleted_cfd_bundle/_corrected_fem.json")
    a = ax[1]
    k = 0
    for t, mk in (("broadband", "o"), ("resonant_tone", "s")):
        recs = c["records"].get(t, [])
        grp = {}
        for rec in recs:
            grp.setdefault((rec["source_corner"], rec["payload_case"]), []).append(
                (rec["mesh_size"], rec["robust"]["robust_value"]))
        for (corner, pay), pts in sorted(grp.items()):
            pts.sort(reverse=True)
            prim = corner == "qualification" and pay == "fill_055"
            a.plot(*zip(*pts), mk + "-", ms=4, lw=2 if prim else 0.8, alpha=1 if prim else 0.45,
                   color=plt.cm.tab10(k % 10),
                   label=f"{corner} / {pay} / {t.replace('_', ' ')}" + (" (PRIMARY)" if prim else ""))
            k += 1
    a.set_title("Atlas: primary corrected FEM, deterministic impedance table\n"
                "source corner / payload / forcing; record outcome: UNRESOLVED (targeted case failed)", fontsize=9)
    for a in ax:
        a.axhline(T_DB, color="k", ls=":", label=f"T = {T_DB} dB")
        a.set_xlabel("FEM mesh size (m)")
        a.set_ylabel("robust FEM noise reduction,\nworst of 4 FEM corners (dB)")
        a.invert_xaxis()
        a.grid(alpha=0.3)
        a.set_ylim(0, None)
        a.legend(fontsize=6.5, ncol=2)
    stamp(fig, SRC + "  Neither record is a PASS; shown to check FEM levels and mesh trend only.")
    fig.tight_layout(rect=(0, 0.03, 1, 1))
    save(fig, out / "F4_fem_vs_target.png", dpi=130)
    plt.close(fig)


