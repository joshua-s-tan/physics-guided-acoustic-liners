def _sha(p):
    import hashlib
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def manifest(out):
    import platform
    import subprocess
    import matplotlib as mpl
    import scipy

    def git(*a):
        return subprocess.run(["git", *a], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    script = Path(__file__).resolve()
    rel = script.relative_to(ROOT).as_posix()
    figs = {}
    for f in sorted(out.glob("*.png")):
        key = f.stem.split("_")[1] if f.stem.split("_")[0] in VEH else f.stem.split("_")[0]
        veh = f.stem.split("_")[0] if f.stem.split("_")[0] in VEH else "both"
        figs[f.name] = dict(sha256=_sha(f), figure=key, vehicle=veh, classification=FIG_CLASS[key])
    m = dict(schema=SC.schema("figure-manifest"),
             note="Figures render frozen records only; they are not evidence and change no record.",
             script=dict(path=rel, sha256=_sha(script), git_head=git("rev-parse", "HEAD"),
                         script_dirty=bool(git("status", "--porcelain", "--", rel))),
             versions=dict(python=platform.python_version(), matplotlib=mpl.__version__,
                           numpy=np.__version__, scipy=scipy.__version__),
             vehicles={v: dict(scenario=VEH[v]["dir"],
                               scenario_hash=load(VDIR / VEH[v]["dir"] / "verdict/verdict.json")["evidence"]
                               .get("scenario_hash"),
                               sources={s: _sha(VDIR / s) for s in SOURCES[v]}) for v in VEH},
             figures=figs)
    (out / "figure_manifest.json").write_text(json.dumps(m, indent=1, sort_keys=True), encoding="utf-8")


def main():
    from .. import cli
    if cli.show_help("figures", "vehicles"):
        return
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else VDIR / "figures/frozen"
    out.mkdir(parents=True, exist_ok=True)
    for v in VEH:
        fig_impedance(v, out)
        pe = pair_estimates(v)
        extra = [(f"[var] {p['case']}", ev) for p, _, ev in pe]
        fig_gates(v, out, extra)
        fig_pairs(v, out, pe)
    fig_fem(out)
    fig_ledger(out)
    manifest(out)
    print("\n".join(sorted(str(p) for p in out.glob("*.png"))))


if __name__ == "__main__":
    main()
