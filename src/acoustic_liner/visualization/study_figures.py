def _sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def manifest(out):
    import matplotlib as mpl
    import scipy

    def git(*a):
        return subprocess.run(["git", *a], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    script = Path(__file__).resolve()
    rel = script.relative_to(ROOT).as_posix()
    m = dict(schema=SC.schema("figure-manifest"),
             note="Figures render frozen records only; intervals are copied from the records, not re-estimated.",
             script=dict(path=rel, sha256=_sha(script), git_head=git("rev-parse", "HEAD"),
                         script_dirty=bool(git("status", "--porcelain", "--", rel))),
             versions=dict(python=platform.python_version(), matplotlib=mpl.__version__, numpy=np.__version__,
                           scipy=scipy.__version__),
             # the frozen final record's checkpoint block, quoted unchanged: its source hashes are historical
             historical_checkpoint=load(RUN / "final_physgen_v1.json")["checkpoint"],
             checkpoint_manifest=dict(path="release/checkpoint-manifest.json",
                                      sha256=_sha(ROOT / "release" / "checkpoint-manifest.json")),
             sources={s: _sha(ROOT / s) for s in SOURCES},
             figures={f.name: dict(sha256=_sha(f), classification=FIG_CLASS[f.stem.split("_")[0]])
                      for f in sorted(out.glob("M*.png"))})
    (out / "figure_manifest.json").write_text(json.dumps(m, indent=1, sort_keys=True), encoding="utf-8")


