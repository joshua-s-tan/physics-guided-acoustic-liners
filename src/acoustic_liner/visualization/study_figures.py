NOTES = {}      # image name -> {"titles": [...], "notes": [...]}, written to TITLES.md / FOOTNOTES.md


def save(fig, path, **kw):
    """Save with no title, suptitle or footnote on the image. Their text goes to TITLES.md / FOOTNOTES.md in the same folder
    (bookkeeping, and the source for the written captions). Footnotes are figure-level texts and any axes text
    tagged gid="footnote"."""
    path = Path(path)
    titles, notes = [], []
    if fig._suptitle is not None and fig._suptitle.get_text():
        titles.append(fig._suptitle.get_text())
        fig._suptitle.remove()
        fig._suptitle = None
    for a in fig.axes:
        for loc in ("left", "center", "right"):
            if a.get_title(loc):
                titles.append(a.get_title(loc))
                a.set_title("", loc=loc)
        for t in list(a.texts):
            if t.get_gid() == "footnote":
                notes.append(t.get_text())
                t.remove()
    for t in list(fig.texts):
        notes.append(t.get_text())
        t.remove()
    NOTES[path.name] = dict(titles=titles, notes=notes)
    _write_readme(path.parent)
    kw.setdefault("bbox_inches", "tight")
    fig.savefig(path, **kw)


def _write_readme(folder):
    src = Path(__file__).resolve().relative_to(ROOT).as_posix()
    for fname, key, head, what in (
            ("TITLES.md", "titles", "Figure and panel titles",
             "The images carry no titles; the title of each figure and panel (in drawing order) is kept here."),
            ("FOOTNOTES.md", "notes", "Figure footnotes",
             "The images carry no footnotes; each figure's source line and notes are kept here.")):
        lines = [f"# {head}", "", f"Bookkeeping, generated by `{src}`. {what} Image hashes are in "
                 "`figure_manifest.json`.", ""]
        for name in sorted(NOTES):
            lines += [f"## {name}", ""]
            lines += ["- " + " ".join(t.split()) for t in NOTES[name][key]] or ["- (none)"]
            lines.append("")
        (Path(folder) / fname).write_text("\n".join(lines), encoding="utf-8")



def load(p):
    return json.loads(Path(p).read_text(encoding="utf-8"))


def stamp(fig, text=SRC):
    """Footer wrapped to the figure width; returns the bottom margin (figure fraction) it needs."""
    import textwrap
    w = fig.get_size_inches()
    lines = [ln for part in text.split("\n") for ln in textwrap.wrap(part, int(w[0] * 17))]
    fig.text(0.01, 0.005, "\n".join(lines), fontsize=7, color="0.4", ha="left", va="bottom")
    return (len(lines) * 0.13 + 0.08) / w[1]


def cond_means(rec, budget, arm):
    """{cond_index: mean best_val over the paired seeds} for one budget and method."""
    acc = {}
    for c in rec["cells"]:
        if c["budget"] == budget:
            acc.setdefault(c["cond_index"], []).append(c[arm]["best_val"])
    return {k: float(np.mean(v)) for k, v in acc.items()}


