# ---------------------------------------------------------------- M4: gate scorecard
def gate_rows(pil, dev, fin):
    from ..evaluation import study as ST
    rows = []

    def add(stage, name, quantity, thr, val, ok):
        rows.append([stage, name, quantity, thr, val, "PASS" if ok else "FAIL"])
    pg = ST.pilot_gates(pil)["gates"]
    assert pg == pil["gates"], "pilot gates do not reproduce the record"
    pa = pil["aggregate"]
    add("pilot (go / no-go)", "D_minus_A_128_nonnegative", "mean D − A, B128", ">= 0",
        f"{pa['128']['D_minus_A']['mean']:+.3f}", pg["D_minus_A_128_nonnegative"])
    add("pilot (go / no-go)", "raw_feasibility_ge_098", "min raw proposal feasibility", ">= 0.98",
        f"{min(b['raw_proposal_feasibility'] for b in pa.values()):.3f}", pg["raw_feasibility_ge_098"])
    add("pilot (go / no-go)", "unique_ge_095", "min unique fraction", ">= 0.95",
        f"{min(b['unique_fraction'] for b in pa.values()):.3f}", pg["unique_ge_095"])
    add("pilot (go / no-go)", "winners_feasible_in_budget", "all winners feasible and mass-compliant", "all",
        "yes" if pg["winners_feasible_in_budget"] else "no", pg["winners_feasible_in_budget"])
    seed_eff = [v for b in pa.values() for k in ("D_minus_A", "D_minus_B") if b[k] for v in b[k]["seed_means"].values()]
    add("pilot (go / no-go)", "no_seed_mean_below_minus_003", "min seed-mean effect", ">= -0.03",
        f"{min(seed_eff):+.3f}", pg["no_seed_mean_below_minus_003"])
    add("pilot (go / no-go)", "ood_complete", "OOD class for every condition", "all",
        "yes" if pg["ood_complete"] else "no", pg["ood_complete"])
    for stage, rec, g in (("development (promotion)", dev, ST.development_gates(dev)["gates"]),
                          ("final (confirmatory, locked method)", fin, fin["gates"])):
        a, b5 = rec["aggregate"]["128"], rec["aggregate"]["512"]
        da, db = a["D_minus_A"], a["D_minus_B"]
        add(stage, "D_minus_A_128", "mean; CI lower, B128", ">= 0.03; > 0",
            f"{da['mean']:+.3f}; {da['ci95'][0]:+.3f}", g["D_minus_A_128"])
        add(stage, "D_minus_B_128", "mean; CI lower, B128", ">= 0.03; > 0",
            f"{db['mean']:+.3f}; {db['ci95'][0]:+.3f}", g["D_minus_B_128"])
        add(stage, "no_negative_seed_mean_128", "min seed mean (D−A, D−B), B128", ">= 0",
            f"{min(da['min_seed_mean'], db['min_seed_mean']):+.3f}", g["no_negative_seed_mean_128"])
        add(stage, "raw_feasibility_ge_098", "raw proposal feasibility, B128", ">= 0.98",
            f"{a['raw_proposal_feasibility']:.3f}", g["raw_feasibility_ge_098"])
        add(stage, "unique_ge_095", "unique fraction, B128", ">= 0.95", f"{a['unique_fraction']:.3f}",
            g["unique_ge_095"])
        add(stage, "winner_feasibility_eq_1", "winner feasibility, all methods, B128", "= 1", "1" if
            g["winner_feasibility_eq_1"] else "<1", g["winner_feasibility_eq_1"])
        add(stage, "winner_mass_eq_1", "winner mass compliance, all methods, B128", "= 1", "1" if
            g["winner_mass_eq_1"] else "<1", g["winner_mass_eq_1"])
        add(stage, "D_not_worse_than_A_512", "mean D − A, B512", ">= -0.03", f"{b5['D_minus_A']['mean']:+.3f}",
            g["D_not_worse_than_A_512"])
        add(stage, "ood_complete", "OOD class for every condition", "all", "yes" if g["ood_complete"] else "no",
            g["ood_complete"])
    return rows


def m4(pil, dev, fin, out):
    rows = gate_rows(pil, dev, fin)
    fig, ax = plt.subplots(figsize=(13, 0.26 * len(rows) + 0.8))
    ax.axis("off")
    tb = ax.table(cellText=rows, colLabels=["stage", "gate", "quantity", "threshold", "value", "result"],
                  loc="center", cellLoc="left", colWidths=[0.2, 0.2, 0.27, 0.1, 0.13, 0.07])
    tb.auto_set_font_size(False)
    tb.set_fontsize(7.5)
    tb.scale(1, 1.3)
    shade = {"pilot": "#eef3fb", "development": "#f6f6f6", "final": "#eef8ee"}
    for i, r in enumerate(rows, start=1):
        for j in range(6):
            tb[i, j].set_facecolor(next(v for k, v in shade.items() if r[0].startswith(k)))
        tb[i, 5].set_text_props(color="darkgreen" if r[5] == "PASS" else "darkred", weight="bold")
    ax.set_title("LinerGen preregistered gates by stage: the method was selected and promoted before the final "
                 "split, which only confirmed the locked method", fontsize=9)
    _bm = stamp(fig, SRC + "  Development gates recomputed from the record with the committed gate function "
          "(study_physgen_v1.development_gates); pilot gates checked equal to the record.")
    fig.tight_layout(rect=(0, _bm, 1, 1))
    save(fig, out / "M4_gate_scorecard.png", dpi=140)
    plt.close(fig)


