# ---------------------------------------------------------------- M2: absolute quality vs budget
def m2(fin, out):
    budgets = fin["budgets"]
    fig, ax = plt.subplots(figsize=(9.5, 5.6))
    for k, arm in enumerate("ABD"):
        x = np.arange(len(budgets)) + (k - 1) * 0.2
        for xi, b in zip(x, budgets):
            v = np.array(list(cond_means(fin, b, arm).values()))
            q1, med, q3 = np.percentile(v, [25, 50, 75])
            ax.plot([xi] * len(v), v, ".", color=ARM[arm][1], alpha=0.15, ms=4)
            ax.errorbar(xi, med, yerr=[[med - q1], [q3 - med]], fmt="s", color=ARM[arm][1], capsize=4, ms=6)
        ax.plot([], [], "s", color=ARM[arm][1], label=ARM[arm][0])
    vc = np.array(list(cond_means(fin, 128, "C").values()))
    ax.axhspan(*np.percentile(vc, [25, 75]), color=ARM["C"][1], alpha=0.12)
    ax.axhline(np.median(vc), color=ARM["C"][1], ls="--", label=ARM["C"][0] + " (32 evaluations; median, IQR)")
    ax.set_xticks(range(len(budgets)), [f"budget {b}" for b in budgets])
    ax.set_ylabel("best robust dB found (mean over seeds, per condition)")
    ax.set_title("Final split: absolute quality at the three recorded budgets\n"
                 "(square: median over conditions; bar: interquartile range; dots: conditions)", fontsize=9)
    ax.legend(fontsize=7.5, loc="upper center", bbox_to_anchor=(0.5, -0.1), ncol=2)
    ax.grid(alpha=0.3, axis="y")
    _bm = stamp(fig, SRC + "  Only budgets 128/512/2048 were recorded; no trajectory is interpolated.")
    fig.tight_layout(rect=(0, _bm, 1, 1))
    save(fig, out / "M2_quality_vs_budget.png", dpi=140)
