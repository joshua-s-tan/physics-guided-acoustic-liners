def _sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def manifest(out, pngs):
    import matplotlib as mpl

    def git(*a):
        return subprocess.run(["git", *a], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    script = Path(__file__).resolve()
    rel = script.relative_to(ROOT).as_posix()
    m = dict(schema=SC.schema("figure-manifest"),
             note="Figure 1 renders frozen records and committed physics code only; it changes no record.",
             script=dict(path=rel, sha256=_sha(script), git_head=git("rev-parse", "HEAD"),
                         script_dirty=bool(git("status", "--porcelain", "--", rel))),
             versions=dict(python=platform.python_version(), matplotlib=mpl.__version__, numpy=np.__version__),
             example_design="frozen Falcon 9 finalist (finalist.json), primary source corner west_range",
             sources={Path(s).relative_to(ROOT).as_posix(): _sha(s) for s in SOURCES},
             figures={q.name: dict(sha256=_sha(q), classification="visualization-only (problem and physics model)")
                      for q in pngs})
    (out / "figure_manifest.json").write_text(json.dumps(m, indent=1, sort_keys=True), encoding="utf-8")


def main():
    from .. import cli
    if cli.show_help("figures", "physics"):
        return
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "artifacts/dev/vehicle_v1/figures/fig1"
    out.mkdir(parents=True, exist_ok=True)
    fin, fem = load(VDIR / "finalist.json"), load(VDIR / "initial_fem.json")
    fig = plt.figure(figsize=(17, 12.5))
    gs = fig.add_gridspec(2, 3, width_ratios=[0.8, 1.15, 1.25], hspace=0.42, wspace=0.32)
    panel_a(fig.add_subplot(gs[0, 0]), fin, geometry())
    panel_b(fig.add_subplot(gs[0, 1]), fin)
    panel_c(fig.add_subplot(gs[0, 2]), fin)
    panel_f(fig.add_subplot(gs[1, 0]))
    panel_d(fig.add_subplot(gs[1, 1]), fin, fem)
    panel_e(fig.add_subplot(gs[1, 2]), fin, fem)
    fig.suptitle("Figure 1. Problem and physics model: a four-bank Helmholtz resonator liner in a representative "
                 "Falcon 9 fairing (example design: frozen Falcon 9 finalist)", fontsize=11)
    fig.text(0.01, 0.005, SRC, fontsize=7, color="0.4")
    png = out / "fig1_physics_model.png"
    save(fig, png, dpi=150, bbox_inches="tight")
    plt.close(fig)
    pngs = [png]
    # the same six panels, each as its own file (identical drawing code)
    singles = [("a_fairing", (5.2, 7.5), lambda ax: panel_a(ax, fin, geometry())),
               ("b_resonator_cell", (6.5, 7.0), lambda ax: panel_b(ax, fin)),
               ("c_absorption_spectrum", (7.5, 6.0), lambda ax: panel_c(ax, fin)),
               ("d_band_noise_reduction", (7.5, 6.0), lambda ax: panel_d(ax, fin, fem)),
               ("e_robust_objective", (7.5, 6.0), lambda ax: panel_e(ax, fin, fem)),
               ("f_fidelity_ladder", (5.5, 6.5), panel_f)]
    for name, size, draw in singles:
        f1 = plt.figure(figsize=size)
        draw(f1.add_subplot(111))
        f1.text(0.01, -0.02, SRC, fontsize=6, color="0.4", wrap=True)
        q = out / f"fig1{name}.png"
        save(f1, q, dpi=200, bbox_inches="tight")
        plt.close(f1)
        pngs.append(q)
    manifest(out, pngs)
    for q in pngs:
        print(q)


if __name__ == "__main__":
    main()
