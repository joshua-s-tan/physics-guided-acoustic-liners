# ---------------------------------------------------------------- (d) per-band noise reduction, oracle vs FEM
def panel_d(ax, fin, fem):
    des, c = fin["design"], fin["conditions"]["primary"]
    band = np.array(O2.DESIGN_BAND_HZ, float)
    rec = next(r for r in fem["records"] if r["source_corner"] == "west_range"
               and r["payload_case"] == "equal_blocked_area_solid" and r["mesh_size"] == 0.1)
    corner = next(cc for cc in rec["corners"] if tuple(cc["corner_id"]) == ("kappa_hi", "low"))
    nr_or = O2.partial_nr_band(O2._a_band(des), O2.ALPHA_BARE_NOMINAL, fin["coverage"], c["A_wall"],
                               corner["kappa"] * c["A_wall"])
    x = np.arange(band.size)
    ax.bar(x - 0.2, nr_or, 0.4, color="tab:purple", alpha=0.75, label="reduced-order oracle (diffuse field, Sabine)")
    ax.bar(x + 0.2, corner["nr_band"], 0.4, color="tab:cyan", alpha=0.85,
           label="payload-resolving FEM (mesh 0.1 m)")
    ax2 = ax.twinx()
    ax2.plot(x, c["weights"], "k.--", lw=0.8, label="band energy weight in ΔOASPL")
    ax2.set_ylim(0, max(c["weights"]) * 2.2)
    ax2.set_ylabel("energy weight", color="0.3")
    ax.axhline(0, color="k", lw=0.8)
    ax.set_xticks(x, [f"{b:g}" for b in band])
    ax.set_xlabel("1/3-octave band (Hz)")
    ax.set_ylabel("interior noise reduction NR (dB)")
    ax.grid(alpha=0.3, axis="y")
    h1, l1 = ax.get_legend_handles_labels()
    h2, l2 = ax2.get_legend_handles_labels()
    ax.legend(h1 + h2, l1 + l2, fontsize=6.5, loc="upper center", bbox_to_anchor=(0.5, -0.13), ncol=2)
    ax.set_title(f"(d) Per-band noise reduction, same design, κ = {corner['kappa']:.3f}, α_bare = "
                 f"{O2.ALPHA_BARE_NOMINAL}", fontsize=9, loc="left")


# ---------------------------------------------------------------- (e) robust objective
def panel_e(ax, fin, fem):
    des, c = fin["design"], fin["conditions"]["primary"]
    ab = O2._a_band(des)
    k0, dk = c["kappa"], O2.DELTA_KAPPA
    ag = np.linspace(*O2.ALPHA_BARE_RANGE, 41)
    kg = np.linspace(max(0, k0 - dk), k0 + dk, 41)
    Z = np.array([[O2.delta_oaspl(O2.partial_nr_band(ab, a, fin["coverage"], c["A_wall"], k * c["A_wall"]),
                                  c["spl"]) for a in ag] for k in kg])
    im = ax.pcolormesh(ag, kg, Z, cmap="viridis", shading="auto")
    plt.colorbar(im, ax=ax, label="ΔOASPL (dB), reduced-order oracle")
    worst = PS.quality_eval_exact(des, c)["best_val"]
    i, j = np.unravel_index(Z.argmin(), Z.shape)
    ax.plot(ag[j], kg[i], "rv", ms=9, clip_on=False, label=f"worst point: {worst:.3f} dB (recorded {fin['primary_dOASPL']:.3f})")
    ax.plot(O2.ALPHA_BARE_NOMINAL, k0, "w+", ms=10, mew=2, label="nominal")
    ax.set_xlabel("bare-wall absorption α_bare (assumed)")
    ax.set_ylabel("κ = A_other / A_wall (assumed background loss)")
    rec = next(r for r in fem["records"] if r["source_corner"] == "west_range"
               and r["payload_case"] == "equal_blocked_area_solid" and r["mesh_size"] == 0.1)
    txt = "payload-resolving FEM, 4 corners (0.1 m):\n" + "\n".join(
        f"  {cc['corner_id'][0]}/{cc['corner_id'][1]}: {cc['value']:.3f} dB" for cc in rec["corners"]) + \
        f"\n  robust (worst) = {rec['robust']['robust_value']:.3f} dB\n  target T = {T_DB} dB"
    ax.text(0.03, 0.97, txt, transform=ax.transAxes, fontsize=6.5, va="top", family="monospace",
            bbox=dict(fc="w", ec="0.7", alpha=0.85))
    ax.legend(fontsize=6.5, loc="lower left")
    ax.set_title("(e) Robust objective: the design is scored by its WORST case", fontsize=9, loc="left")


# ---------------------------------------------------------------- (f) fidelity ladder
