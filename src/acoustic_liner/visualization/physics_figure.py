# ---------------------------------------------------------------- (b) design variables
def panel_b(ax, fin):
    des = fin["design"]
    Dm = des["D"] * 1000
    g0 = des["groups"][0]
    S = RM.neck_area(g0["r_neck"])
    Le = RM.effective_neck_length(g0["L_neck"], g0["r_neck"])
    V = RM.cavity_volume_for_target_f0(g0["f0"], S, Le)
    w = np.sqrt(V / des["D"]) * 1000                 # cell side (mm) for a square cell of depth D
    r, L = g0["r_neck"] * 1000, g0["L_neck"] * 1000
    x0 = 0
    ax.add_patch(Rectangle((x0, 0), w, Dm, fc="#eef3fb", ec="k", lw=1.2))
    ax.add_patch(Rectangle((x0 + w / 2 - r, Dm - L), 2 * r, L, fc="w", ec="tab:blue", lw=1.2))
    ax.plot([x0, x0 + w / 2 - r], [Dm, Dm], color="k", lw=3)
    ax.plot([x0 + w / 2 + r, x0 + w], [Dm, Dm], color="k", lw=3)
    ax.annotate("", (x0 - 6, Dm), (x0 - 6, 0), arrowprops=dict(arrowstyle="<->"))
    ax.text(x0 - 8, Dm / 2, f"D = {Dm:.0f} mm", rotation=90, ha="right", va="center", fontsize=7)
    ax.annotate("", (x0 + w / 2 + r, Dm + 4), (x0 + w / 2 - r, Dm + 4), arrowprops=dict(arrowstyle="<->"))
    ax.text(x0 + w / 2, Dm + 6, f"2r = {2 * r:.1f} mm", ha="center", fontsize=7)
    ax.text(x0 + w / 2 + r + 2, Dm - L / 2, f"L = {L:.1f} mm", fontsize=7, va="center", color="tab:blue")
    ax.text(x0 + w / 2, 6, "cavity", ha="center", fontsize=7.5)
