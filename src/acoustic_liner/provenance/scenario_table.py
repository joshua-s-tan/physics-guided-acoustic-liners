"""Write docs/VEHICLE-SCENARIO-PROVENANCE.md: one field-by-field provenance table per vehicle scenario, generated from
the YAML (the single source of truth) so the table cannot drift from it.
"""
import sys
from pathlib import Path

from .. import paths  # noqa: E402
from ..vehicles import scenarios as V


def rows(node, sources, path=""):
    if isinstance(node, dict) and "class" in node and "value" in node:
        v = node["value"]
        v = (f"{len(v)} values: {v[0]} ... {v[-1]}" if isinstance(v, list) and len(v) > 8 else v)
        src = sources.get(node.get("source"), {}).get("title", "") if node.get("source") else ""
        lim = node.get("limitation", "") + (f" [{node['label']}]" if node.get("label") else "")
        yield [path.lstrip("."), str(v), node.get("units", ""), node["class"], src, node.get("ref", ""),
               node.get("derivation", ""), lim]
    elif isinstance(node, dict):
        for k, x in node.items():
            yield from rows(x, sources, f"{path}.{k}")


def table(sc):
    d = sc.raw
    out = [f"## `{sc.name}`", "", f"File `configs/{Path(sc.path).name}` Â· scenario hash `{sc.scenario_hash}` Â· "
           f"kind `{d['scenario_kind']}`", "",
           "| YAML field | value | units | classification | source document | page / table / figure | derivation | limitation |",
           "|---|---|---|---|---|---|---|---|"]
    for blk in ("geometry", "spectrum", "source_conditions", "acoustics", "payload_geometry", "payload_model"):
        if blk in d:
            for r in rows(d[blk], d["sources"], blk):
                out.append("| " + " | ".join(str(c).replace("|", "/").replace("\n", " ") for c in r) + " |")
    g = sc.geometry
    out += ["", f"Derived at load: lined wall area {g.lined_wall_area:.9f} mÂ², cavity volume {g.cavity_volume:.9f} mÂ³.",
            *[f"Source corner `{c['id']}` ({role}): computed OASPL {c['oaspl_computed']:.9f} dB vs published "
              f"{c['oaspl_published']} dB; 50â€“250 Hz {V.oaspl(c['model_levels']):.9f} dB; model bands "
              f"{c['model_levels']}." for role, c in sc.corners.items()]]
    if hasattr(sc, "payload_equivalent"):
        e = sc.payload_equivalent
        out += ["", f"Payload axisymmetric equivalent (`{e['name']}`, not CAD): one-volume plan area "
                f"{e['plan_area_one_volume_m2']:.6f} mÂ², axis to inner face {e['axis_to_inner_face_m']:.4f} m, blocked "
                f"area {e['blocked_area_m2']:.6f} mÂ², R_max {e['R_max_m']:.4f} m, r_in {e['r_in_m']:.6f} m, axial "
                f"extent {e['axial_extent_m']:.4f} m, displaced volume {e['displaced_volume_m3']:.6f} mÂ³; equations: "
                + "; ".join(e["equations"]) + "."]
    for cid, c in getattr(sc, "payload_cases", {}).items():
        out.append(f"FEM payload case `{cid}` ({c['role']}, {c['shape']}): r {c['r_in_m']:.6f}..{c['r_out_m']:.6f} m, "
                   f"z {c['z_base_m']:.6f}..{c['z_top_m']:.6f} m, blocked area {c['blocked_area_m2']:.6f} m², fluid "
                   f"volume {c['fluid_volume_m3']:.6f} m³, geometry hash `{c['geometry_sha256']}`, BC hash `{c['bc_sha256']}`.")
    return out


if __name__ == "__main__":
    from .. import cli
    if cli.show_help("provenance", "scenario-table"):
        raise SystemExit(0)
    text = ["# Vehicle scenario provenance (generated by `acoustic-liner provenance scenario-table`; do not edit by hand)", ""]
    for sc in (V.falcon9_unblanketed(), V.atlas_i_14ft()):
        text += table(sc) + [""]
    (paths.ROOT / "docs" / "VEHICLE-SCENARIO-PROVENANCE.md").write_text("\n".join(text), encoding="utf-8")
    print("wrote docs/VEHICLE-SCENARIO-PROVENANCE.md")
