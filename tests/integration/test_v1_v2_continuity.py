def test_mid_anchor_is_centered_and_distinct():
    """True center-out 'mid' placement: its facet set is centered and differs from both low and high."""
    mesh = _build_shared_mesh()
    tagged = MESH.tag_boundary_facets(mesh)
    pts = mesh.p
    zc = {f: 0.5 * (pts[1, mesh.facets[0, f]] + pts[1, mesh.facets[1, f]]) for f in tagged["sets"]["wall"]}
    zlo, zhi = min(zc.values()), max(zc.values())
    zmid = 0.5 * (zlo + zhi)
    cov = 0.4
    low = MESH.select_coverage_facets(mesh, tagged, cov, anchor="low")
    high = MESH.select_coverage_facets(mesh, tagged, cov, anchor="high")
    mid = MESH.select_coverage_facets(mesh, tagged, cov, anchor="mid")
    assert mid != low and mid != high                     # no longer aliased to low
    mean_z = lambda s: sum(zc[f] for f in s) / len(s)
    # mid band is centered near mid-height; low sits below it, high above it
    assert abs(mean_z(mid) - zmid) < abs(mean_z(low) - zmid)
    assert abs(mean_z(mid) - zmid) < abs(mean_z(high) - zmid)
    assert mean_z(low) < mean_z(mid) < mean_z(high)
    # the runner solves partial coverage for every anchor (bare_beta required)
    for a in ("low", "high", "mid"):
        ev = FS.run_scenario_fem(SCEN, DESIGN_BANDS, wall_beta=BETA_WALL, coverage=cov,
                                 bare_beta=0.01 + 0j, anchor=a)
        assert ev["coverage"] == cov and ev["anchor"] == a
        assert all(np.isfinite(v) and v > 0 for v in ev["ms_by_freq"].values())


def test_coverage_invariant_over_full_range():
    """Requested coverage is authoritative; achieved mesh coverage recorded separately. Exercise the ENTIRE
    allowed coverage range (including full=1 and zero=0, which are trivially exact) for every anchor; the
    invariant must hold within the mesh-resolution acceptance threshold. If any valid coverage exceeded it,
    this test would FAIL (the fix is a finer mesh, not a looser threshold)."""
    covs = [round(0.1 * i, 1) for i in range(0, 11)]     # 0.0, 0.1, ..., 1.0
    for cov in covs:
        for a in ("low", "high", "mid"):
            ev = FS.run_scenario_fem(SCEN, DESIGN_BANDS, wall_beta=BETA_WALL, coverage=cov,
                                     bare_beta=0.01 + 0j, anchor=a)
            cc = ev["coverage_consistency"]
            assert cc is not None                                    # present for full AND zero too
            assert cc["requested_coverage"] == cov
            assert cc["mass_treated_area"] == pytest.approx(cov * SCEN.A_wall)   # mass uses REQUESTED
            for key in ("achieved_mesh_coverage", "treated_mesh_area", "mass_treated_area",
                        "mesh_wall_area", "abs_coverage_error", "tol", "passed"):
                assert key in cc
            assert cc["abs_coverage_error"] <= FS.COVERAGE_CONSISTENCY_TOL     # ABSOLUTE coverage-fraction error
    # full and zero are exact
    full = FS.run_scenario_fem(SCEN, DESIGN_BANDS, wall_beta=BETA_WALL, coverage=1.0)["coverage_consistency"]
    assert full["achieved_mesh_coverage"] == pytest.approx(1.0)
    zero = FS.run_scenario_fem(SCEN, DESIGN_BANDS, wall_beta=BETA_WALL, coverage=0.0,
                               bare_beta=0.01 + 0j)["coverage_consistency"]
    assert zero["achieved_mesh_coverage"] == pytest.approx(0.0)


