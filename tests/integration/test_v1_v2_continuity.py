def _spectrum_weights():
    e = np.array([10.0 ** (L / 10.0) for L in SCEN.spl_dB])
    return e / e.sum()


def test_migrated_solver_matches_v1_full_coverage():
    """The MIGRATED production solver matches the FROZEN v1 reference (committed fixture) at full coverage:
    Falcon-weighted |dB| <= 0.02, max per-band <= 0.05, tracking v1 across a fine grid with matching NR sign."""
    mesh = _build_shared_mesh()                                   # mesh fingerprint asserted == fixture inside
    tagged = MESH.tag_boundary_facets(mesh)

    v1_band = np.asarray(V1REF["v1_band_ms"], float)
    d_band = np.array([10.0 * np.log10(FS.solve_interior(mesh, f, tagged, wall_beta=BETA_WALL, A_other=0.0) / v1)
                       for f, v1 in zip(DESIGN_BANDS, v1_band)])
    weighted = float(np.sum(_spectrum_weights() * np.abs(d_band)))
    assert weighted <= 0.02, f"Falcon-weighted |dB| {weighted} > 0.02"
    assert np.abs(d_band).max() <= 0.05, f"max per-band |dB| {np.abs(d_band).max()} > 0.05"

    # fine grid: track the frozen v1 everywhere + matching NR sign
    grid = np.asarray(V1REF["grid_hz"], float)
    v1g = np.asarray(V1REF["v1_grid_ms"], float)
    v1r = np.asarray(V1REF["v1_rigid_grid_ms"], float)
    relg = np.array([FS.solve_interior(mesh, f, tagged, wall_beta=BETA_WALL, A_other=0.0) for f in grid])
    assert np.abs(10.0 * np.log10(relg / v1g)).max() <= 0.05
    nr_v1 = 10.0 * np.log10(v1r / v1g); nr_rel = 10.0 * np.log10(v1r / relg)
    assert np.all(np.sign(nr_v1) == np.sign(nr_rel))


def test_kernel_is_fail_closed():
    mesh = _build_shared_mesh()
    tagged = MESH.tag_boundary_facets(mesh)
    wall = tagged["sets"]["wall"]
    # negative / NaN A_other rejected (no silent zero)
    with pytest.raises(FERR.FEMSolverError):
        FS.solve_interior(mesh, 100.0, tagged, wall_beta=BETA_WALL, A_other=-1.0, volume=187.6)
    with pytest.raises(FERR.FEMSolverError):
        FS.solve_interior(mesh, 100.0, tagged, wall_beta=BETA_WALL, A_other=float("nan"), volume=187.6)
    # A_other>0 with bad volume rejected
    with pytest.raises(FERR.FEMSolverError):
        FS.solve_interior(mesh, 100.0, tagged, wall_beta=BETA_WALL, A_other=40.0, volume=0.0)
    # active (non-passive) wall beta rejected
    with pytest.raises(FERR.FEMSolverError):
        FS.solve_interior(mesh, 100.0, tagged, wall_beta=-0.5 + 0j)
    # foreign treated facet rejected
    foreign = max(tagged["all"]) + 999
    with pytest.raises(FERR.FEMSolverError):
        FS.solve_interior(mesh, 100.0, tagged, wall_beta=BETA_WALL, treated_facets={foreign})
    # partial coverage without bare_beta rejected (no silent rigid)
    some = set(list(wall)[:5])
    with pytest.raises(FERR.FEMSolverError):
        FS.solve_interior(mesh, 100.0, tagged, wall_beta=BETA_WALL, treated_facets=some)
    # non-bool base_radiation rejected
    with pytest.raises(FERR.FEMSolverError):
        FS.solve_interior(mesh, 100.0, tagged, wall_beta=BETA_WALL, base_radiation=1)


def test_generic_boundary_vs_volume_sensitivity():
    """#3: generic-benchmark explicit-boundary vs volumetric solve on the IDENTICAL mesh/source/wall config,
    with geometry-derived disjoint tags, real area/volume checks, and the mandatory production diffuse
    round-trip. Result is a generic model-form SENSITIVITY, explicitly outside the Falcon envelope."""
    from acoustic_liner.fem.verification import reference_cavity as RC
    from acoustic_liner.fem import boundary as FB
    cav = RC.ReferenceCavity(name="generic_boundary_benchmark_v1", R_outer=2.6, H=10.0,
                             R_payload=1.5, H_payload=4.0, max_A_other=43.6)
    ev = RC.run_reference_cavity_benchmark(cav, SCEN.band_hz, wall_beta=BETA_WALL, A_other=40.0)
    assert ev["interpretation"] == "generic_benchmark_model_form_sensitivity"
    assert "NOT part of the Falcon robustness envelope" in ev["note"]
    # geometry-derived disjoint tags matched the analytic cavity (partition ran + areas match)
    assert ev["measured_source_area"] == pytest.approx(cav.source_area, rel=0.03)
    assert ev["measured_wall_area"] == pytest.approx(cav.lined_wall_area, rel=0.03)
    assert ev["measured_S_other"] == pytest.approx(cav.S_other, rel=0.03)
    assert ev["measured_volume"] == pytest.approx(cav.fluid_volume, rel=0.03)
    # mandatory diffuse round-trip closed; units via beta=Z_air*Y
    assert ev["roundtrip_error"] <= ev["roundtrip_tol"]
    assert ev["payload_beta"]["real"] == pytest.approx(FS.Z_AIR * ev["payload_admittance"]["real"], rel=1e-9)
    # expanded evidence schema present (frozen before verify_release)
    for key in ("freqs", "mesh_size", "area_tol", "air_properties", "source_model", "explicit_a_other_model",
                "volumetric_loss_model", "diffuse_mapping_id", "diffuse_quadrature_n", "delta_convention",
                "geometry_hash", "boundary_partition", "alpha_other_max"):
        assert key in ev
    assert ev["delta_convention"] == "10*log10(explicit_ms/volumetric_ms)"
    assert ev["explicit_a_other_model"]["a_other_model"] == "explicit_other_boundary_admittance"
    assert ev["volumetric_loss_model"]["a_other_model"] == "equivalent_distributed_volumetric_damping"
    assert ev["alpha_other"] <= ev["alpha_other_max"]
    # two solves produced a finite model-form difference (explicit vs volumetric)
    assert all(np.isfinite(v) and v > 0 for v in ev["explicit_ms"].values())
    assert all(np.isfinite(v) and v > 0 for v in ev["volumetric_ms"].values())
    assert np.isfinite(ev["max_abs_delta_dB"])
    # a vehicle scenario must be rejected from the explicit-boundary benchmark path (EXACT exception)
    with pytest.raises(FB.FEMBoundaryError):
        RC.run_reference_cavity_benchmark(SCEN, SCEN.band_hz, wall_beta=BETA_WALL, A_other=40.0)


