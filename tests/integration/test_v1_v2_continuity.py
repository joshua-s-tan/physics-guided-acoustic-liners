def _self_sha256(doc):
    d = {k: v for k, v in doc.items() if k != "self_sha256"}
    return hashlib.sha256(json.dumps(d, sort_keys=True, separators=(",", ":")).encode()).hexdigest()


# fail-closed: a tampered/corrupt fixture must not silently pass the gate
assert V1REF["self_sha256"] == _self_sha256(V1REF), "v1 continuity fixture failed its self SHA-256 check"

SCEN = S.falcon9_2025_blanketed()          # AUTHORITATIVE scenario -- geometry/spectrum/areas come from here
DESIGN_BANDS = SCEN.band_hz
ZETA_WALL = complex(*V1REF["zeta_wall"])
BETA_WALL = 1.0 / ZETA_WALL


def _mesh_fingerprint(mesh):
    p = np.round(np.asarray(mesh.p, float), 9); t = np.asarray(mesh.t, np.int64)
    h = hashlib.sha256()
    h.update(b"p"); h.update(np.ascontiguousarray(p).tobytes())
    h.update(b"t"); h.update(np.ascontiguousarray(t).tobytes())
    h.update(b"shape"); h.update(str((p.shape, t.shape)).encode())
    return h.hexdigest()


def _build_shared_mesh():
    g = SCEN.geometry
    mesh = MESH.build_fairing_interior_mesh(g.R_fair, g.H_barrel, g.H_total, mesh_size=V1REF["mesh_size"])
    # the frozen v1 reference is valid ONLY for the mesh it was computed on; drift => fail-closed (regenerate).
    assert _mesh_fingerprint(mesh) == V1REF["mesh_fingerprint"], (
        "shared mesh drifted from the frozen v1 continuity fixture (toolchain change?); "
        "re-freeze via `acoustic-liner provenance continuity-fixture` after review")
    return mesh


def test_real_mesh_matches_authoritative_scenario():
    """Bind to the authoritative scenario: mesh from scenario.geometry; the REAL mesh-integrated wall area and
    physical volume must satisfy assert_fem_consistency against scenario.A_wall / scenario.volume (not
    duplicated constants). Also proves the disjoint facet partition."""
    mesh = _build_shared_mesh()
    tagged = MESH.tag_boundary_facets(mesh)
    expected = {"source": math.pi*SCEN.geometry.R_fair**2, "wall": SCEN.A_wall, "axis": 0.0}
    MESH.assert_boundary_partition(tagged, expected)                # disjoint + union==all + computed areas
    mesh_wall = sum(tagged["area_by_id"][f] for f in tagged["sets"]["wall"])
    mesh_vol = MESH.mesh_physical_volume(mesh)
    # the load-bearing check: real mesh area AND physical volume are consistent with the authoritative scenario
    S.assert_fem_consistency(SCEN, mesh_wall, mesh_vol, SCEN.A_other_nominal, expected_kappa=SCEN.kappa_nominal)
    assert mesh_wall == pytest.approx(SCEN.A_wall, rel=5e-3)
    assert mesh_vol == pytest.approx(SCEN.volume, rel=5e-3)


def test_scenario_bound_runner_produces_consistent_evidence():
    """The production runner binds mesh->measured area/volume->partition gate->consistency->A_other->solve->
    evidence, with reproducible structured coefficients."""
    from acoustic_liner.evaluation import requests as R
    ev = FS.run_scenario_fem(SCEN, DESIGN_BANDS, wall_beta=BETA_WALL)   # full coverage, Falcon volumetric A_other
    assert ev["scenario_name"] == "falcon9_2025_blanketed"
    assert ev["scenario_sha256"] == R.canonical_scenario_sha256(SCEN)   # exact canonical hash, not just len 64
    assert ev["measured_wall_area"] == pytest.approx(SCEN.A_wall, rel=5e-3)
    assert ev["measured_volume"] == pytest.approx(SCEN.volume, rel=5e-3)
    assert ev["boundary_partition"]["wall"] < 0.01                     # partition gate ran inside the runner
    assert ev["source_model"]["source_model"] == "v1_base_radiation_plus_incident"
    assert ev["damping_model"]["a_other_model"] == "equivalent_distributed_volumetric_damping"
    assert all(np.isfinite(v) and v > 0 for v in ev["ms_by_freq"].values())
    # structured per-frequency beta (real/imag), not a string
    b = ev["boundary_coeffs"]["wall_beta_by_freq"][float(DESIGN_BANDS[0])]
    assert b["real"] == pytest.approx(1.0 / 3.0) and b["imag"] == pytest.approx(0.0)


